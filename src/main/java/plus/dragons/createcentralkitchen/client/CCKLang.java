package plus.dragons.createcentralkitchen.client;

import com.zurrtum.create.client.catnip.lang.LangBuilder;
import com.zurrtum.create.client.catnip.lang.LangNumberFormat;
import org.jetbrains.annotations.ApiStatus.Internal;
import plus.dragons.createcentralkitchen.common.CCKCommon;

/** Translatable text for Ponder scenes. The strings themselves live in the lang files. */
@Internal
public class CCKLang {
    public static LangBuilder builder() {
        return new LangBuilder(CCKCommon.ID);
    }

    public static LangBuilder number(double d) {
        return builder().text(LangNumberFormat.format(d));
    }

    public static LangBuilder text(String text) {
        return builder().text(text);
    }

    public static LangBuilder translate(String key, Object... args) {
        return builder().translate(key, args);
    }
}
